import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("org.jetbrains.kotlin.plugin.compose")
}

/**
 * The CPU types the Rust core is built for: phones (64- and 32-bit ARM) by default. The emulator (x86_64)
 * only when asked — `./gradlew :app:assembleDebug -PrustAbis=x86_64` — so the universal APK carries phone
 * libraries only (each copy of the core is ~1 MB compressed).
 */
val abis = providers.gradleProperty("rustAbis").orNull?.split(",")?.map { it.trim() }?.filter { it.isNotEmpty() }
    ?: listOf("arm64-v8a", "armeabi-v7a")

android {
    // Side by side with the TWA (io.github.quoterg.ironnotes) until the cut-over (docs/NATIVE.md).
    namespace = "io.github.quoterg.ironnotes.next"
    compileSdk = 36
    ndkVersion = "28.2.13676358"

    defaultConfig {
        minSdk = 24
        targetSdk = 36
        versionCode = 1
        versionName = "0.1.0"
    }

    // Two builds of the same app (docs/NATIVE.md "Never offline"):
    // - next: "Iron Notes Next", installs beside the current app (the TWA) — the beta;
    // - stable: the cut-over (N11) — the TWA's own package and name, a higher version code, so it installs as an
    //   update over the TWA when signed with the same upload key.
    flavorDimensions += "release"
    productFlavors {
        create("next") {
            dimension = "release"
            applicationId = "io.github.quoterg.ironnotes.next"
            resValue("string", "app_name", "Iron Notes Next")
        }
        create("stable") {
            dimension = "release"
            applicationId = "io.github.quoterg.ironnotes"
            // Above the TWA's last version code (android/twa-manifest.json appVersionCode 2).
            versionCode = 100
            versionName = "2.0.0"
            resValue("string", "app_name", "Iron Notes")
        }
    }

    splits {
        // One APK per CPU type (each phone downloads only its own Rust library) plus a universal one.
        abi {
            isEnable = true
            reset()
            include(*abis.toTypedArray())
            isUniversalApk = true
        }
    }

    // The owner's upload key (never committed): native/keystore.properties with storeFile, storePassword,
    // keyAlias, keyPassword (docs/NATIVE.md "Release"). Without it — CI — release builds use the debug key, only
    // so the size budget can be checked on a shrunk build; a stable release then refuses to build (below).
    val keystoreProps = rootProject.file("keystore.properties")
    if (keystoreProps.exists()) {
        val props = Properties().apply { keystoreProps.inputStream().use { load(it) } }
        fun required(key: String): String = props.getProperty(key)?.trim()?.takeIf { it.isNotEmpty() }
            ?: throw GradleException("native/keystore.properties: \"$key\" is missing (docs/NATIVE.md \"Release\")")
        val store = rootProject.file(required("storeFile"))
        if (!store.exists()) throw GradleException("native/keystore.properties: storeFile not found: $store")
        signingConfigs.create("upload") {
            storeFile = store
            storePassword = required("storePassword")
            keyAlias = required("keyAlias")
            keyPassword = required("keyPassword")
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("upload") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = false
        resValues = true
    }

    packaging {
        resources.excludes += setOf("/META-INF/{AL2.0,LGPL2.1}", "DebugProbesKt.bin", "kotlin-tooling-metadata.json")
    }

    dependenciesInfo {
        // No Google-encrypted dependency blob in the APK (F-Droid friendly).
        includeInApk = false
        includeInBundle = false
    }

    sourceSets["main"].jniLibs.srcDir(layout.buildDirectory.dir("rust/jniLibs"))
    sourceSets["main"].java.srcDir(layout.buildDirectory.dir("generated/uniffi"))
}

kotlin {
    compilerOptions.jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
}

// ---- The Rust core (native/core-rs): built per CPU type, Kotlin bindings generated by UniFFI ----

val rustDir = rootProject.file("core-rs")
val cargo = File(System.getProperty("user.home"), ".cargo/bin/cargo").takeIf { it.exists() }?.path ?: "cargo"
val jniOut = layout.buildDirectory.dir("rust/jniLibs")
val bindingsOut = layout.buildDirectory.dir("generated/uniffi")
val ndkDir = androidComponents.sdkComponents.ndkDirectory

val cargoNdk by tasks.registering(Exec::class) {
    description = "Builds the Rust core for each CPU type (cargo-ndk)."
    inputs.dir(rustDir.resolve("src"))
    inputs.files(rustDir.resolve("Cargo.toml"), rustDir.resolve("Cargo.lock"))
    outputs.dir(jniOut)
    workingDir(rustDir)
    // Only the requested CPU types end up in the APK: libraries of an earlier build with other types go.
    inputs.property("abis", abis)
    doFirst {
        delete(jniOut)
        environment("ANDROID_NDK_HOME", ndkDir.get().asFile.path)
    }
    commandLine(
        listOf(cargo, "ndk") + abis.flatMap { listOf("-t", it) } +
            listOf("--platform", "24", "-o", jniOut.get().asFile.path, "build", "--release", "--lib"),
    )
}

val rustHostLib by tasks.registering(Exec::class) {
    description = "Builds the Rust core for this computer: the bindings are generated from it (the Android " +
        "libraries are stripped, which removes the metadata UniFFI reads)."
    inputs.dir(rustDir.resolve("src"))
    inputs.files(rustDir.resolve("Cargo.toml"), rustDir.resolve("Cargo.lock"))
    outputs.dir(rustDir.resolve("target/debug"))
    workingDir(rustDir)
    commandLine(cargo, "build", "--quiet", "--lib")
}

val uniffiBindings by tasks.registering(Exec::class) {
    description = "Generates the Kotlin API of the Rust core (UniFFI)."
    dependsOn(rustHostLib)
    inputs.dir(rustDir.resolve("src"))
    inputs.files(rustDir.resolve("Cargo.toml"), rustDir.resolve("Cargo.lock"), rustDir.resolve("uniffi.toml"))
    outputs.dir(bindingsOut)
    workingDir(rustDir)
    commandLine(
        cargo, "run", "--quiet", "--features", "bindgen", "--bin", "uniffi-bindgen", "--",
        "generate", "--library", rustDir.resolve("target/debug/${System.mapLibraryName("iron_core")}").path,
        "--language", "kotlin", "--no-format", "--out-dir", bindingsOut.get().asFile.path,
    )
}

// Unit tests run on this computer and load the Rust core through JNA (the host library built above).
tasks.withType<Test>().configureEach {
    dependsOn(rustHostLib)
    systemProperty("jna.library.path", rustDir.resolve("target/debug").path)
}

tasks.named("preBuild") { dependsOn(cargoNdk, uniffiBindings) }

