// ---- The Rust core (native/core-rs): built per CPU type, Kotlin bindings generated by UniFFI ----

val rustDir = rootProject.file("core-rs")
val cargo = File(System.getProperty("user.home"), ".cargo/bin/cargo").takeIf { it.exists() }?.path ?: "cargo"
val jniOut = layout.buildDirectory.dir("rust/jniLibs")
val bindingsOut = layout.buildDirectory.dir("generated/uniffi")
val ndkDir = androidComponents.sdkComponents.ndkDirectory

val cargoNdk by tasks.registering(Exec::class) {
    description = "Builds the Rust core for each CPU type (cargo-ndk)."
    inputs.dir(rustDir.resolve("src"))
    inputs.files(rustDir.resolve("Cargo.toml"), rustDir.resolve("Cargo.lock"))
    outputs.dir(jniOut)
    workingDir(rustDir)
    // Only the requested CPU types end up in the APK: libraries of an earlier build with other types go.
    inputs.property("abis", abis)
    doFirst {
        delete(jniOut)
        environment("ANDROID_NDK_HOME", ndkDir.get().asFile.path)
    }
    commandLine(
        listOf(cargo, "ndk") + abis.flatMap { listOf("-t", it) } +
            listOf("--platform", "24", "-o", jniOut.get().asFile.path, "build", "--release", "--lib"),
    )
}

val rustHostLib by tasks.registering(Exec::class) {
    description = "Builds the Rust core for this computer: the bindings are generated from it (the Android " +
        "libraries are stripped, which removes the metadata UniFFI reads)."
    inputs.dir(rustDir.resolve("src"))
    inputs.files(rustDir.resolve("Cargo.toml"), rustDir.resolve("Cargo.lock"))
    outputs.dir(rustDir.resolve("target/debug"))
    workingDir(rustDir)
    commandLine(cargo, "build", "--quiet", "--lib")
}

val uniffiBindings by tasks.registering(Exec::class) {
    description = "Generates the Kotlin API of the Rust core (UniFFI)."
    dependsOn(rustHostLib)
    inputs.dir(rustDir.resolve("src"))
    inputs.files(rustDir.resolve("Cargo.toml"), rustDir.resolve("Cargo.lock"), rustDir.resolve("uniffi.toml"))
    outputs.dir(bindingsOut)
    workingDir(rustDir)
    commandLine(
        cargo, "run", "--quiet", "--features", "bindgen", "--bin", "uniffi-bindgen", "--",
        "generate", "--library", rustDir.resolve("target/debug/${System.mapLibraryName("iron_core")}").path,
        "--language", "kotlin", "--no-format", "--out-dir", bindingsOut.get().asFile.path,
    )
}

// Unit tests run on this computer and load the Rust core through JNA (the host library built above).
tasks.withType<Test>().configureEach {
    dependsOn(rustHostLib)
    systemProperty("jna.library.path", rustDir.resolve("target/debug").path)
}

tasks.named("preBuild") { dependsOn(cargoNdk, uniffiBindings) }

